const PRISMA_ALLOWLIST: AllowlistEntry[] = [...SCOPED_ALLOWLIST, ...EXEMPT_ALLOWLIST];

/** The core's call sites: `ee/` directories are the Enterprise suite's (D-238). */
const discoverCoreCallSites = () =>
  discoverPrismaCallSites(SOURCE_ROOT, { skipDirectories: ['ee'] });

describe('Prisma call-site ownership allowlist', () => {
  it('allowlists every production Prisma call site by enclosing scope and checks ownership tokens', () => {
    const actual = discoverCoreCallSites();
    const actualKeys = actual.map(callSiteKey).sort();
    const listedKeys = PRISMA_ALLOWLIST.map(callSiteKey).sort();

    expect(new Set(listedKeys).size).toBe(listedKeys.length);
    expect(actualKeys).toEqual(listedKeys);
    expect(unlistedCallSites(actual, PRISMA_ALLOWLIST)).toEqual([]);

    for (const entry of SCOPED_ALLOWLIST) {
      const site = actual.find((candidate) => callSiteKey(candidate) === callSiteKey(entry));
      expect(site, `missing scoped call site ${callSiteKey(entry)}`).toBeDefined();
      expect(site?.sourceText).toContain(entry.ownershipToken);
    }

    for (const entry of EXEMPT_ALLOWLIST) {
      expect(entry.reason.length, `uncommented exemption ${callSiteKey(entry)}`).toBeGreaterThan(
        20,
      );
    }
  });

  it('fails closed when an existing allowlist entry is removed', () => {
    const actual = discoverCoreCallSites();
    const reducedAllowlist = PRISMA_ALLOWLIST.slice(0, -1);
    const removed = PRISMA_ALLOWLIST.at(-1);

    expect(removed).toBeDefined();
    expect(unlistedCallSites(actual, reducedAllowlist).map(callSiteKey)).toEqual([
      callSiteKey(removed!),
    ]);
  });

  it('rejects a new Prisma call site that is not explicitly listed', () => {
    const fixture = `
      class FutureService {
        constructor(private readonly prisma: unknown) {}
        leak(id: string) {
          return this.prisma.attachment.findFirst({ where: { id } });
        }
      }
    `;
    const actual = parsePrismaCallSites('fixture.ts', fixture);

    expect(unlistedCallSites(actual, [])).toHaveLength(1);
    expect(callSiteKey(actual[0]!)).toBe(
      'fixture.ts#FutureService.leak:prisma.attachment.findFirst',
    );
  });

  it('keeps keys stable when lines are added or removed above a Prisma call', () => {
    const before = `
      class StableService {
        constructor(private readonly prisma: unknown) {}
        find(userId: string) {
          return this.prisma.bot.findFirst({ where: { userId } });
        }
      }
    `;
    const after = `
      // Added comments and helpers above should not churn the allowlist.
      const noop = () => undefined;
      class StableService {
        constructor(private readonly prisma: unknown) {}
        helper() { return noop(); }
        find(userId: string) {
          return this.prisma.bot.findFirst({ where: { userId } });
        }
      }
    `;
    expect(parsePrismaCallSites('stable.ts', after).map(callSiteKey)).toEqual(
      parsePrismaCallSites('stable.ts', before).map(callSiteKey),
    );
  });

  it('discovers raw SQL, which arrives as a tagged template rather than a call', () => {
    const fixture = [
      'class FutureService {',
      '  constructor(private readonly prisma: unknown) {}',
      '  leak(id: string) {',
      '    return this.prisma.$queryRaw`SELECT * FROM "Bot" WHERE id = ${id}`;',
      '  }',
      '}',
    ].join('\n');
    const actual = parsePrismaCallSites('fixture.ts', fixture);

    expect(unlistedCallSites(actual, [])).toHaveLength(1);
    expect(callSiteKey(actual[0]!)).toBe('fixture.ts#FutureService.leak:prisma.$client.$queryRaw');
  });

  it('discovers static computed access and rejects dynamic model or operation names', () => {
    const fixture = `
      class FutureService {
        constructor(private readonly prisma: unknown) {}
        staticModel(id: string) {
          return this.prisma['attachment'].findFirst({ where: { id } });
        }
        staticOperation(id: string) {
          return this.prisma.attachment['findFirst']({ where: { id } });
        }
        dynamicModel(model: string, id: string) {
          return this.prisma[model].findFirst({ where: { id } });
        }
        dynamicOperation(operation: string, id: string) {
          return this.prisma.attachment[operation]({ where: { id } });
        }
      }
    `;
    const actual = parsePrismaCallSites('fixture.ts', fixture);
    const staticSites = actual.filter(
      (site) => site.model === 'attachment' && site.operation === 'findFirst',
    );
    const staticAllowlist = staticSites.map((site) => ({
      ...site,
      policy: 'exempt' as const,
      reason: 'Static computed-access regression fixture.',
    }));
    const dynamicSites = unlistedCallSites(actual, staticAllowlist);

    expect(staticSites).toHaveLength(2);
    expect(staticSites.every((site) => site.sourceText.includes('findFirst'))).toBe(true);
    expect(dynamicSites).toHaveLength(2);
    expect(dynamicSites.map((site) => `${site.model}.${site.operation}`)).toEqual([
      '<computed>.findFirst',
      'attachment.<computed>',
    ]);
  });
});
