import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from 'vitest';
import { EventType } from '@tanstack/ai';
import { PrismaService } from '../src/prisma/prisma.service.js';
import { RunLeaseService } from '../src/agent/persistence/run-lease.js';
import { createRunEventLog, RunEventWakeups } from '../src/agent/persistence/run-event-log.js';
import { signIn, signOutAndDelete, type SignedInUser } from './auth-fixture.js';
import { ownedThread, produceOwned } from './mod-ai06-owned-harness.js';

describe.skipIf(!process.env['DATABASE_URL'])('D-206 failed owned producer (real db)', () => {
  const prisma = new PrismaService();
  let owner: SignedInUser;
  beforeAll(async () => {
    await prisma.$connect();
    owner = await signIn(prisma, { label: 'producerfailure' });
  });
  afterEach(() => vi.restoreAllMocks());
  afterAll(async () => {
    await signOutAndDelete(prisma, owner.userId);
    await prisma.$disconnect();
  });

  it('settles a delivery failure after a tool result instead of leaving a closed running run', async () => {
    const f = await ownedThread(prisma, owner.userId);
    const effect = vi.fn(async () => 'fixture tool result');
    let toolReturned = false;
    const failure = new Error('private delivery detail');
    await expect(
      produceOwned(prisma, f, f.first, effect, undefined, {
        mode: 'FULL',
        ports: {
          appendEvent: async (event) => {
            if (event.type === EventType.TOOL_CALL_RESULT) toolReturned = true;
            if (toolReturned && event.type === EventType.TEXT_MESSAGE_CONTENT) throw failure;
          },
        },
      }),
    ).rejects.toThrow(failure);
    expect(effect).toHaveBeenCalledTimes(1);
    const run = await prisma.agentTurn.findFirstOrThrow({
      where: { id: f.first.runId, bot: { userId: owner.userId } },
    });
    expect(run).toMatchObject({
      status: 'failed',
      activeKey: null,
      workerId: null,
      leaseExpiresAt: null,
    });
    expect(run.endedAt).not.toBeNull();
    expect(run.eventsClosedAt).not.toBeNull();
    const replay = await createRunEventLog(prisma, f.first, {
      wakeups: new RunEventWakeups(),
    }).snapshot();
    expect(replay.at(-1)?.chunk.type).toBe(EventType.RUN_ERROR);
    expect(JSON.stringify(replay)).not.toContain('private delivery detail');
    expect(await new RunLeaseService(prisma).expiredCandidates()).not.toContainEqual(
      expect.objectContaining({ runId: f.first.runId }),
    );
  });

  it('settles even when the durable append fails, without emitting a successful finish', async () => {
    // The fault below picks its event by reading the chunk's type in SQL, which
    // a sealed chunk does not show (D-236), so this one case runs unsealed —
    // from before its thread is written, so that every row of it reads back.
    vi.stubEnv('CREWAID_CREDENTIAL_KEYRING', '');
    const f = await ownedThread(prisma, owner.userId);
    // The UUID is generated by the owned fixture. This constraint makes the
    // actual transactional append fail; mocking the root delegate misses tx.
    await prisma.$executeRawUnsafe(
      `ALTER TABLE "RunEvent" ADD CONSTRAINT d206_append_fault CHECK ("runId" <> '${f.first.runId}' OR chunk->>'type' <> 'TEXT_MESSAGE_CONTENT')`,
    );
    try {
      await expect(
        produceOwned(prisma, f, f.first, async () => 'result', undefined, { mode: 'FULL' }),
      ).rejects.toThrow();
    } finally {
      vi.unstubAllEnvs();
      await prisma.$executeRaw`ALTER TABLE "RunEvent" DROP CONSTRAINT d206_append_fault`;
    }
    const run = await prisma.agentTurn.findFirstOrThrow({
      where: { id: f.first.runId, bot: { userId: owner.userId } },
    });
    expect(run).toMatchObject({ status: 'failed', activeKey: null, workerId: null });
    const replay = await createRunEventLog(prisma, f.first, {
      wakeups: new RunEventWakeups(),
    }).snapshot();
    expect(replay.some(({ chunk }) => chunk.type === EventType.RUN_FINISHED)).toBe(false);
    expect(replay.at(-1)?.chunk.type).toBe(EventType.RUN_ERROR);
    expect(JSON.stringify(replay)).not.toContain('d206_append_fault');
  });

  it('cannot settle or close the log of a replacement owner', async () => {
    const f = await ownedThread(prisma, owner.userId);
    const leases = new RunLeaseService(prisma);
    let replacement: typeof f.first | undefined;
    await expect(
      produceOwned(prisma, f, f.first, async () => 'result', undefined, {
        mode: 'FULL',
        ports: {
          appendEvent: async (event) => {
            if (event.type !== EventType.TOOL_CALL_RESULT) return;
            await leases.release(f.first);
            const claim = await leases.claim({ ...f, runId: f.first.runId });
            if (claim.kind !== 'claimed') throw new Error('fixture replacement failed');
            replacement = claim.lease;
            throw new Error('old producer delivery failed');
          },
        },
      }),
    ).rejects.toThrow();
    expect(replacement).toBeDefined();
    const run = await prisma.agentTurn.findFirstOrThrow({
      where: { id: f.first.runId, bot: { userId: owner.userId } },
    });
    expect(run).toMatchObject({
      status: 'running',
      eventsClosedAt: null,
      workerId: replacement!.workerId,
      driverEpoch: replacement!.epoch,
    });
    await leases.finish(replacement!, 'aborted');
  });

  it('retains an open log and expires the lease when failed settlement cannot commit', async () => {
    const f = await ownedThread(prisma, owner.userId);
    await prisma.$executeRawUnsafe(
      `ALTER TABLE "AgentTurn" ADD CONSTRAINT d206_settle_fault CHECK (id <> '${f.first.runId}' OR status <> 'failed')`,
    );
    try {
      await expect(
        produceOwned(prisma, f, f.first, async () => 'result', undefined, {
          mode: 'FULL',
          ports: {
            appendEvent: async (event) => {
              if (event.type === EventType.TOOL_CALL_RESULT) throw new Error('delivery failed');
            },
          },
        }),
      ).rejects.toThrow();
      const run = await prisma.agentTurn.findFirstOrThrow({
        where: { id: f.first.runId, bot: { userId: owner.userId } },
      });
      expect(run).toMatchObject({
        status: 'running',
        eventsClosedAt: null,
        workerId: f.first.workerId,
      });
      expect(run.leaseExpiresAt!.getTime()).toBeLessThanOrEqual(Date.now());
    } finally {
      await prisma.$executeRaw`ALTER TABLE "AgentTurn" DROP CONSTRAINT d206_settle_fault`;
    }
    const leases = new RunLeaseService(prisma);
    const recovered = await leases.claim({ ...f, runId: f.first.runId });
    expect(recovered.kind).toBe('claimed');
    if (recovered.kind === 'claimed') await leases.finish(recovered.lease, 'aborted');
  });
});
