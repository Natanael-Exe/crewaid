"""Derive animated clay layers from the approved transparent masters.

Run with Python, Pillow and NumPy. Originals remain the source of truth.
The face and clay texture stay raster artwork; isolated features can blink/look.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'packages/brand/assets/mascots'
OUT.mkdir(parents=True, exist_ok=True)
IDS = ['circle', 'square', 'polygon', 'egg', 'bulb', 'cloud', 'shield', 'splat']
SIZE = 384
metadata = []

for ident in IDS:
    original = Image.open(ROOT / f'packages/brand/masters/mascots/clay/{ident}.png').convert('RGBA')
    # Normalize the complete character, including the hands/feet, to a 90% reach.
    a = np.asarray(original)
    ys, xs = np.where(a[:, :, 3] > 128)
    box = (int(xs.min()), int(ys.min()), int(xs.max()+1), int(ys.max()+1))
    cut = original.crop(box)
    cut.thumbnail((round(SIZE*.9), round(SIZE*.9)), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (SIZE, SIZE))
    canvas.paste(cut, ((SIZE-cut.width)//2, (SIZE-cut.height)//2))
    pixels = np.asarray(canvas).copy()
    rgb = pixels[:, :, :3].astype(float)
    low, high = rgb.min(2), rgb.max(2)
    yy, xx = np.indices((SIZE, SIZE))
    # Only the central face can contain features: exclude the contact shadow.
    dark = (high < 115) & ((high-low) < 35) & (pixels[:, :, 3] > 200)
    dark &= (xx > SIZE*.23) & (xx < SIZE*.77) & (yy > SIZE*.25) & (yy < SIZE*.72)
    seen = np.zeros_like(dark)
    components = []
    for y,x in zip(*np.where(dark)):
        if seen[y,x]: continue
        stack, points = [(y,x)], []
        seen[y,x] = True
        while stack:
            py,px = stack.pop(); points.append((py,px))
            for dy,dx in [(0,1),(0,-1),(1,0),(-1,0)]:
                ny,nx = py+dy,px+dx
                if 0 <= ny < SIZE and 0 <= nx < SIZE and dark[ny,nx] and not seen[ny,nx]:
                    seen[ny,nx] = True; stack.append((ny,nx))
        if len(points) > 40: components.append(points)
    components = sorted(components, key=len, reverse=True)[:3]
    if len(components) != 3: raise ValueError(f'{ident}: expected eyes and nose, got {len(components)}')
    components.sort(key=lambda c: np.mean([p[1] for p in c]))
    feature_masks = []
    for points in components:
        mask = np.zeros((SIZE,SIZE), dtype=np.uint8)
        for y,x in points: mask[y,x] = 255
        feature_masks.append(np.asarray(Image.fromarray(mask).filter(ImageFilter.MaxFilter(9))) > 0)
    remove = np.logical_or.reduce(feature_masks)
    # Diffuse neutral face pixels through feature holes. This removes baked-in eyes
    # without flattening the recessed face's texture or rim lighting.
    clean = rgb.copy()
    clean[remove] = [235,235,235]
    for _ in range(500):
        neighbors = (np.roll(clean,1,0)+np.roll(clean,-1,0)+np.roll(clean,1,1)+np.roll(clean,-1,1))/4
        clean[remove] = neighbors[remove]
    saturation = (high-low) / np.maximum(high,1)
    face = (saturation < .16) & (low > 100) & (xx > SIZE*.18) & (xx < SIZE*.82) & (yy > SIZE*.2) & (yy < SIZE*.8)
    face |= remove
    # Soften the edge by one pixel; preserve actual neutral face shading.
    face_alpha = np.asarray(Image.fromarray((face*255).astype('uint8')).filter(ImageFilter.GaussianBlur(.6))) / 255
    base_alpha = pixels[:,:,3]
    body = pixels.copy()
    luminance = clean @ np.array([.2126,.7152,.0722])
    middle = np.median(luminance[(saturation>.25)&(base_alpha>240)])
    shade = np.clip(luminance / middle * 127.5,0,255).astype('uint8')
    body[:,:,:3] = shade[:,:,None]
    body[:,:,3] = base_alpha
    neutral = pixels.copy(); neutral[:,:,:3] = np.clip(clean,0,255).astype('uint8')
    neutral[:,:,3] = np.round(base_alpha * face_alpha).astype('uint8')
    eye_mask = feature_masks[0] | feature_masks[2]
    feature_layers = []
    for mask in [eye_mask,feature_masks[1]]:
        layer = pixels.copy()
        coverage = np.clip((clean-rgb).max(2)/30,0,1)
        layer[:,:,3] = np.round(base_alpha * mask * coverage).astype('uint8')
        feature_layers.append(layer)
    layers = [body,neutral,*feature_layers]
    for name,layer in zip(['body','face','eyes','nose'],layers):
        Image.fromarray(layer).save(OUT/f'{ident}-{name}.webp',quality=92,alpha_quality=100,method=6)
    ey,ex = np.where(eye_mask)
    metadata.append({'id':ident,'eyeCenter': [round(float(ex.mean())/SIZE*100,3),round(float(ey.mean())/SIZE*100,3)]})
    print(ident, 'eye center',metadata[-1]['eyeCenter'])
(ROOT/'packages/brand/src/clay-geometry.ts').write_text('/** Generated by tools/generate-mascot-layers.py. */\nexport const CLAY_GEOMETRY = '+json.dumps(metadata,indent=2)+' as const;\n')
