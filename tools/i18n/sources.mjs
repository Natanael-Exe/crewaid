/**
 * D-234/D-235: every English source the app is translated from, and every
 * place a translation is written to, as one flat set of "units".
 *
 * A unit is `source:id` → message. The app's catalog is already flat (its
 * values are strings or plural objects); the other sources are nested data,
 * flattened to dotted paths and rebuilt in the English shape on write, so a
 * translation can never change a structure the code reads.
 *
 * Run through tsx (or vitest): the sources are TypeScript.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { en } from '../../apps/desktop/src/renderer/i18n/messages/en.ts';
import { MENU_LABELS_EN } from '../../apps/desktop/src/applicationMenu.ts';
import { MENU_TRANSLATIONS } from '../../apps/desktop/src/menuTranslations.ts';
import { WELCOME_COPY_EN } from '../../packages/shared/src/welcome.ts';
import { WELCOME_TRANSLATIONS } from '../../packages/shared/src/welcome-translations.ts';
import { TEMPLATE_WORDS_EN } from '../../apps/orchestrator/src/experience/template-catalog.ts';
import { FAILURE_COPY_EN } from '../../apps/orchestrator/src/models/failure-copy.ts';
import { SERVER_TRANSLATIONS } from '../../apps/orchestrator/src/i18n/locales/index.ts';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const APP_LOCALES = join(ROOT, 'apps/desktop/src/renderer/i18n/locales');
const WELCOME_FILE = join(ROOT, 'packages/shared/src/welcome-translations.ts');
const SERVER_DIR = join(ROOT, 'apps/orchestrator/src/i18n/locales');
const MENU_FILE = join(ROOT, 'apps/desktop/src/menuTranslations.ts');
export const GLOSSARY_DIR = join(ROOT, 'tools/i18n/glossary');
const SNAPSHOT_FILE = join(ROOT, 'tools/i18n/translated-from.json');

const GENERATED =
  '// Generated by tools/i18n/translate.mjs from the English source. Do not edit by hand:\n' +
  '// change the English, then run `pnpm i18n:translate`.\n';

/** Where each source's English lives and where its translations are read from. */
const SOURCES = {
  app: { english: en, flat: true, read: (locale) => readJson(join(APP_LOCALES, `${locale}.json`)) },
  welcome: { english: WELCOME_COPY_EN, read: (locale) => WELCOME_TRANSLATIONS[locale] },
  templates: {
    english: TEMPLATE_WORDS_EN,
    read: (locale) => SERVER_TRANSLATIONS[locale]?.templates,
  },
  failures: { english: FAILURE_COPY_EN, read: (locale) => SERVER_TRANSLATIONS[locale]?.failures },
  menu: { english: MENU_LABELS_EN, read: (locale) => MENU_TRANSLATIONS[locale] },
};
export const SOURCE_NAMES = Object.keys(SOURCES);

function readJson(path) {
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : undefined;
}

export function flatten(value, prefix = '', out = {}) {
  if (typeof value === 'string') {
    out[prefix] = value;
  } else if (Array.isArray(value)) {
    value.forEach((item, index) =>
      flatten(item, prefix === '' ? `${index}` : `${prefix}.${index}`, out),
    );
  } else if (value !== null && typeof value === 'object') {
    for (const [key, item] of Object.entries(value))
      flatten(item, prefix === '' ? key : `${prefix}.${key}`, out);
  }
  return out;
}

/** Rebuild `shape` with each leaf taken from `leaves`; undefined if any leaf is missing. */
function unflatten(shape, leaves, prefix = '') {
  const at = (key) => (prefix === '' ? `${key}` : `${prefix}.${key}`);
  if (typeof shape === 'string') return leaves[prefix];
  if (Array.isArray(shape)) {
    const items = shape.map((item, index) => unflatten(item, leaves, at(index)));
    return items.includes(undefined) ? undefined : items;
  }
  const entries = Object.entries(shape).map(([key, item]) => [
    key,
    unflatten(item, leaves, at(key)),
  ]);
  return entries.some(([, item]) => item === undefined) ? undefined : Object.fromEntries(entries);
}

function unitsOf(source, value) {
  if (value === undefined) return {};
  return SOURCES[source].flat ? value : flatten(value);
}

/** Every English unit, `source:id` → message, in source order. */
export function englishUnits() {
  const units = new Map();
  for (const source of SOURCE_NAMES)
    for (const [id, message] of Object.entries(unitsOf(source, SOURCES[source].english)))
      units.set(`${source}:${id}`, message);
  return units;
}

/** What is translated for `locale` now, in the same shape. */
export function translatedUnits(locale) {
  const units = new Map();
  for (const source of SOURCE_NAMES)
    for (const [id, message] of Object.entries(unitsOf(source, SOURCES[source].read(locale))))
      units.set(`${source}:${id}`, message);
  return units;
}

/** The languages that ship: each has an app catalog, which the picker reads. */
export function shippedLocales() {
  if (!existsSync(APP_LOCALES)) return [];
  return readdirSync(APP_LOCALES)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .sort();
}

export function hashOf(message) {
  return createHash('sha256').update(JSON.stringify(message)).digest('hex').slice(0, 12);
}

/** The English each unit's translations were made from, by hash. */
export function readSnapshot() {
  return readJson(SNAPSHOT_FILE) ?? {};
}

export function writeSnapshot(snapshot) {
  const sorted = Object.fromEntries(Object.entries(snapshot).sort(([a], [b]) => (a < b ? -1 : 1)));
  writeFileSync(SNAPSHOT_FILE, `${JSON.stringify(sorted, null, 2)}\n`);
  return SNAPSHOT_FILE;
}

export function readGlossary(locale) {
  return readJson(join(GLOSSARY_DIR, `${locale}.json`));
}

export function writeGlossary(locale, glossary) {
  mkdirSync(GLOSSARY_DIR, { recursive: true });
  const path = join(GLOSSARY_DIR, `${locale}.json`);
  writeFileSync(path, `${JSON.stringify(glossary, null, 2)}\n`);
  return path;
}

function leavesOf(source, units) {
  const prefix = `${source}:`;
  const leaves = {};
  for (const [unit, message] of units)
    if (unit.startsWith(prefix)) leaves[unit.slice(prefix.length)] = message;
  return leaves;
}

const identifier = (locale) => locale.replace(/-(\w)/g, (_, letter) => letter.toUpperCase());

/**
 * Write every locale's translations. `byLocale` maps a locale to all its
 * units (old and new). A nested source is written only when complete: a
 * language with a gap reads English there, and the catalog check says so.
 */
export function writeTranslations(byLocale) {
  const written = [];
  mkdirSync(APP_LOCALES, { recursive: true });
  mkdirSync(SERVER_DIR, { recursive: true });
  const locales = [...byLocale.keys()].sort();
  const welcome = {};
  const menu = {};
  for (const locale of locales) {
    const units = byLocale.get(locale);
    const app = {};
    const leaves = leavesOf('app', units);
    for (const key of Object.keys(en)) if (leaves[key] !== undefined) app[key] = leaves[key];
    const appPath = join(APP_LOCALES, `${locale}.json`);
    writeFileSync(appPath, `${JSON.stringify(app, null, 2)}\n`);
    written.push(appPath);

    const welcomeCopy = unflatten(WELCOME_COPY_EN, leavesOf('welcome', units));
    if (welcomeCopy !== undefined) welcome[locale] = welcomeCopy;
    const labels = unflatten(MENU_LABELS_EN, leavesOf('menu', units));
    if (labels !== undefined) menu[locale] = labels;

    const server = {};
    const templates = unflatten(TEMPLATE_WORDS_EN, leavesOf('templates', units));
    if (templates !== undefined) server.templates = templates;
    const failures = unflatten(FAILURE_COPY_EN, leavesOf('failures', units));
    if (failures !== undefined) server.failures = failures;
    const serverPath = join(SERVER_DIR, `${locale}.ts`);
    writeFileSync(
      serverPath,
      `${GENERATED}import type { ServerCopy } from '../server-copy.js';\n\n` +
        `export const copy: ServerCopy = ${JSON.stringify(server, null, 2)};\n`,
    );
    written.push(serverPath);
  }

  const index = join(SERVER_DIR, 'index.ts');
  writeFileSync(
    index,
    `${GENERATED}import type { Locale } from '@crewaid/shared';\n` +
      `import type { ServerCopy } from '../server-copy.js';\n` +
      locales
        .map((locale) => `import { copy as ${identifier(locale)} } from './${locale}.js';\n`)
        .join('') +
      `\nexport const SERVER_TRANSLATIONS: Readonly<Partial<Record<Locale, ServerCopy>>> = {\n` +
      locales.map((locale) => `  '${locale}': ${identifier(locale)},\n`).join('') +
      `};\n`,
  );
  written.push(index);

  writeFileSync(
    WELCOME_FILE,
    `${GENERATED}import type { Locale } from './locale.js';\nimport type { WelcomeCopyData } from './welcome.js';\n\n` +
      `export const WELCOME_TRANSLATIONS: Readonly<Partial<Record<Locale, WelcomeCopyData>>> = ` +
      `${JSON.stringify(welcome, null, 2)};\n`,
  );
  written.push(WELCOME_FILE);

  writeFileSync(
    MENU_FILE,
    `${GENERATED}import type { Locale } from '@crewaid/shared';\nimport type { MenuLabels } from './applicationMenu.js';\n\n` +
      `export const MENU_TRANSLATIONS: Readonly<Partial<Record<Locale, MenuLabels>>> = ` +
      `${JSON.stringify(menu, null, 2)};\n`,
  );
  written.push(MENU_FILE);
  return written;
}

/** Format what the tool wrote with the repo's own prettier, so a diff shows words, not quotes. */
export function formatFiles(paths) {
  if (paths.length === 0) return;
  execFileSync('pnpm', ['exec', 'prettier', '--write', '--log-level', 'warn', ...paths], {
    cwd: ROOT,
    stdio: 'inherit',
  });
}
